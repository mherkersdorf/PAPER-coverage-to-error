classdef PenaltyTest < matlab.unittest.TestCase
%PENALTYTEST  The soft-constraint penalty of rid.gen.Direct.
%
%   Every test states what input would make it FAIL. A test that cannot name one is
%   decoration, and two of the properties here -- the unit-mean normalization and the
%   centred violation -- are invisible to any check that only looks at the correct
%   implementation. Those two are therefore written as MUTATION checks: the mutant
%   and the real value are computed side by side in the test, and the test asserts
%   they differ in the specific way the specification says they must.
%
%   The expected numbers come, written out
%   by hand, never generated by the code under test.

    properties (Constant)
        Tol = 1e-12
        % The section 4 reference configuration.
        L   = 20
        TW  = 0.1
        VS  = 0.05
    end

    methods (Test)

        % --- gamma: a shape, not a magnitude ---------------------------------

        function gammaHasUnitMeanForEveryHorizonAndTailWeight(tc)
            % Fails if: the /mean(gammaRaw) normalization is dropped -- mean(gamma)
            % becomes mean(gammaRaw), which is 0.399 at the defaults.
            for nHorizon = [2 3 5 20 50]
                for tailWeight = [0.01 0.1 0.5 0.9]
                    gamma = rid.gen.Direct.horizonWeights(nHorizon, tailWeight);
                    tc.verifyEqual(mean(gamma), 1, "AbsTol", 1e-14, ...
                        sprintf("nHorizon = %d, tailWeight = %g", ...
                                nHorizon, tailWeight));
                    tc.verifyEqual(numel(gamma), nHorizon);
                end
            end
        end

        function theEndToStartRatioIsExactlyTailWeight(tc)
            % Fails if: gammaRaw uses a fixed decay rate per step rather than being
            % geometric in (j-1)/(nHorizon-1) -- the ratio would then depend on
            % nHorizon instead of being tailWeight.
            for nHorizon = [2 5 20 50]
                for tailWeight = [0.01 0.1 0.5]
                    gamma = rid.gen.Direct.horizonWeights(nHorizon, tailWeight);
                    tc.verifyEqual(gamma(end) / gamma(1), tailWeight, ...
                        "RelTol", 1e-14);
                end
            end
        end

        function gammaIsHorizonLengthInvariant(tc)
            % Fails if: the decay is per-step. The far end must carry tailWeight of
            % the applied sample's weight whatever the horizon length is.
            horizons = [5 20 50];
            ratios   = zeros(1, numel(horizons));
            for iH = 1:numel(horizons)
                gamma      = rid.gen.Direct.horizonWeights(horizons(iH), 0.1);
                ratios(iH) = gamma(end) / gamma(1);
            end
            tc.verifyEqual(ratios, 0.1 * ones(1, 3), "RelTol", 1e-14);
        end

        function gammaIsOneForAHorizonOfOne(tc)
            % Fails if: the 0/0 in (j-1)/(nHorizon-1) is not special-cased -- gamma
            % becomes NaN and every penalty silently becomes NaN with it.
            gamma = rid.gen.Direct.horizonWeights(1, 0.1);
            tc.verifyEqual(gamma, 1);
            tc.verifyFalse(any(isnan(gamma)));
        end

        % --- the calibration, as a mutation check ----------------------------

        function aSustainedViolationOfViolationScaleCostsExactlyPsiMax(tc)
            % THE calibration statement, and the reason the weight is declared
            % through violationScale rather than as a raw number.
            %
            % Fails if: gamma is left unnormalized (cost becomes 0.399 * psiMax), or
            % the aggregation is a sum rather than a mean (cost becomes 20x), or w
            % is not psiMax/violationScale^2.
            gen  = PenaltyTest.makeGen([-1 1], PenaltyTest.L);
            Zphys = PenaltyTest.uniform(PenaltyTest.L, PenaltyTest.VS, 0, 1);
            pen  = gen.penalty(Zphys, "violationScale", PenaltyTest.VS, ...
                       "tailWeight", PenaltyTest.TW, "psiMax", 1);
            tc.verifyEqual(pen, 1, "AbsTol", 1e-12);

            % The mutant, computed side by side: gamma left unnormalized.
            raw       = PenaltyTest.TW .^ (((1:PenaltyTest.L).' - 1) / (PenaltyTest.L - 1));
            penMutant = (1 / PenaltyTest.VS^2) * mean(raw .* PenaltyTest.VS^2);
            tc.verifyEqual(penMutant, mean(raw), "AbsTol", 1e-12);
            tc.verifyEqual(penMutant, 0.399278, "AbsTol", 1e-5);
            tc.verifyLessThan(penMutant, 0.5);          % demonstrably not psiMax
            tc.verifyNotEqual(round(penMutant, 6), round(pen, 6));
        end

        function theSectionFourTableIsReproduced(tc)
            % The four rows of the method description, which together
            % pin the mean aggregation, the quadratic, and the gamma profile.
            %
            % Fails if: mean becomes sum (row 2 would read 2.5 not 0.125); the
            % quadratic becomes linear (row 4 would read 0.376 not 1.13); gamma
            % becomes flat (rows 2 and 3 would be equal).
            gen = PenaltyTest.makeGen([-1 1], PenaltyTest.L);
            call = @(Zphys) gen.penalty(Zphys, "violationScale", PenaltyTest.VS, ...
                            "tailWeight", PenaltyTest.TW, "psiMax", 1);

            tc.verifyEqual(call(PenaltyTest.uniform(20, 0.05, 0, 1)), ...
                1.00, "AbsTol", 5e-3);                       % sustained 5%
            tc.verifyEqual(call(PenaltyTest.atStep(20, 1,  0.05, 0, 1)), ...
                0.125, "AbsTol", 5e-3);                      % 5% applied only
            tc.verifyEqual(call(PenaltyTest.atStep(20, 20, 0.05, 0, 1)), ...
                0.0125, "AbsTol", 5e-4);                     % 5% last step
            tc.verifyEqual(call(PenaltyTest.atStep(20, 1,  0.15, 0, 1)), ...
                1.13, "AbsTol", 5e-3);                       % 15% applied only
        end

        function aViolationNowCostsTenTimesOneAtTheHorizonEnd(tc)
            % The ratio tailWeight sets, isolated. nHorizon = 20 is chosen because
            % gamma(1)/gamma(20) is then exactly 10 -- large enough that a flat
            % gamma could not pass by tolerance.
            %
            % Fails if: gamma is flat, or the profile is applied back-to-front.
            gen   = PenaltyTest.makeGen([-1 1], 20);
            first = gen.penalty(PenaltyTest.atStep(20, 1,  0.05, 0, 1), ...
                        "tailWeight", 0.1);
            last  = gen.penalty(PenaltyTest.atStep(20, 20, 0.05, 0, 1), ...
                        "tailWeight", 0.1);
            tc.verifyEqual(first / last, 10, "RelTol", 1e-12);
            tc.verifyGreaterThan(first, last);      % direction, not just ratio
        end

        % --- the centred violation, as a mutation check ----------------------

        function theViolationIsMeasuredFromTheBoxCentreNotFromZero(tc)
            % The asymmetric box [-1, 2] is the normal case, not the exception.
            % Writing |g| - c would silently assume gMin = -gMax, and would be wrong
            % in BOTH directions: too strict above and too permissive below.
            %
            % Fails if: v = (abs(g) - gHalf)/s. Both assertions below are needed --
            % the first alone would pass an implementation that is merely shifted.
            gen    = PenaltyTest.makeGen([-1 2], 4);     % gMid 0.5, gHalf 1.5, s 3
            call   = @(g) gen.penalty(PenaltyTest.constant(4, g));
            mutant = @(g) mean(max(0, (abs(g) - 1.5) / 3).^2);

            % Inside the declared box the correct penalty is exactly zero
            % throughout, while the uncentred mutant already charges at g = 1.6.
            for g = [-1 -0.5 0 1 1.6 2]
                tc.verifyEqual(call(g), 0, "AbsTol", tc.Tol, ...
                    sprintf("g = %g is inside [-1, 2]", g));
            end
            tc.verifyGreaterThan(mutant(1.6), 0);   % ... the mutant is not zero

            % Just outside, the correct penalty is positive on BOTH sides, while the
            % mutant is blind to the lower one.
            tc.verifyGreaterThan(call(2.1), 0);
            tc.verifyGreaterThan(call(-1.1), 0);
            tc.verifyEqual(mutant(-1.1), 0, "AbsTol", tc.Tol);
        end

        % --- the hinge -------------------------------------------------------

        function thePenaltyIsExactlyZeroInsideTheLimit(tc)
            % Exactly zero, not merely small: inside the limit the optimizer must
            % feel nothing at all.
            %
            % Fails if: the hinge is replaced by a smooth softplus-style barrier,
            % which is positive everywhere.
            gen = PenaltyTest.makeGen([-1 1], 5);
            for g = [-1 -0.9 0 0.5 1]
                [pen, gradPen] = gen.penalty(PenaltyTest.constant(5, g));
                tc.verifyEqual(pen, 0, "AbsTol", tc.Tol);
                tc.verifyEqual(gradPen, zeros(5, 3), "AbsTol", tc.Tol);
            end
        end

        function thePenaltyIsQuadraticOutsideTheLimit(tc)
            % Fails if: the hinge is linear -- doubling the excess would double the
            % cost rather than quadrupling it.
            gen = PenaltyTest.makeGen([-1 1], 4);
            p1  = gen.penalty(PenaltyTest.constant(4, 1 + 0.10));
            p2  = gen.penalty(PenaltyTest.constant(4, 1 + 0.20));
            tc.verifyEqual(p2 / p1, 4, "RelTol", 1e-12);
        end

        function theHingeIsC1AtTheBoundary(tc)
            % Matched one-sided derivatives, both zero. The left slope is exactly
            % zero; the right slope must vanish LINEARLY in h, which is what
            % distinguishes max(0,v)^2 from max(0,v).
            %
            % Fails if: the hinge is linear -- the right slope is then ~25 and does
            % not shrink with h, which the mutant below computes explicitly.
            gen  = PenaltyTest.makeGen([-1 1], 20);   % boundary at g = 1
            call = @(g) gen.penalty(PenaltyTest.constant(20, g));

            h = 1e-6;
            slopeLeft   = (call(1) - call(1 - h)) / h;
            slopeRightH = (call(1 + h) - call(1)) / h;
            slopeRight2 = (call(1 + 2*h) - call(1)) / (2*h);

            tc.verifyEqual(slopeLeft, 0, "AbsTol", tc.Tol);
            tc.verifyLessThan(abs(slopeRightH), 1e-4);
            tc.verifyEqual(slopeRightH / slopeRight2, 0.5, "RelTol", 1e-6);

            % The linear-hinge mutant, side by side: its right slope is O(1).
            gamma       = rid.gen.Direct.horizonWeights(20, 0.1);
            slopeMutant = (1 / 0.05^2) * mean(gamma) / 2;   % w * dmean(v)/dg
            tc.verifyGreaterThan(slopeMutant, 1);
        end

        % --- the gradient ------------------------------------------------------

        function gradPenMatchesCentralFiniteDifferences(tc)
            % Fails if: the chain rule drops sign(g - gMid), the factor 2, the 1/s,
            % or the 1/nHorizon of the mean.
            gen  = PenaltyTest.makeGen([-1 1], 6);
            Zphys = zeros(6, 3);
            Zphys(:, 3) = [1.4; 0.2; -1.3; 0.0; 1.05; -1.6];   % outside AND inside
            [~, gradPen] = gen.penalty(Zphys);

            h = 1e-6;
            for jStep = 1:6
                Zp = Zphys; Zp(jStep, 3) = Zp(jStep, 3) + h;
                Zm = Zphys; Zm(jStep, 3) = Zm(jStep, 3) - h;
                fd = (gen.penalty(Zp) - gen.penalty(Zm)) / (2 * h);
                tc.verifyEqual(gradPen(jStep, 3), fd, "AbsTol", 1e-6, ...
                    sprintf("step %d", jStep));
            end
            % Non-vacuity: both branches were exercised, so this is not a test that
            % only ever compared zero to zero.
            tc.verifyGreaterThan(sum(gradPen(:, 3) ~= 0), 0);
            tc.verifyGreaterThan(sum(gradPen(:, 3) == 0), 0);
        end

        function gradPenIsShapedLikeZphysAndZeroOnHardDimensions(tc)
            % Fails if: gradPen is returned as d/dtheta, or the soft constraint is
            % written into the wrong column.
            gen  = PenaltyTest.makeGen([-1 1], 6);
            [~, gradPen] = gen.penalty(PenaltyTest.constant(6, 1.5));
            tc.verifyEqual(size(gradPen), [6, 3]);
            tc.verifyEqual(gradPen(:, 1:2), zeros(6, 2), "AbsTol", tc.Tol);
            tc.verifyTrue(all(gradPen(:, 3) > 0));
        end

        % --- the seam to +crit ---------------------------------------------------

        function theCriterionNeverSeesAConstraint(tc)
            % The criterion/objective split as a structural test rather than a numerical one: if +crit ever
            % gains a constraint term, J stops being comparable across runs, P5's
            % bound J <= psiMax becomes false, and the certification statement is
            % meaningless. No unit test of a return value would notice.
            %
            % Fails if: any +crit source file references the generator, the
            % constraint declaration, or the soft-limit knobs.
            %
            % NOT the bare word "penalty": `psi` is the criterion's own CLIPPED
            % PENALTY, so the word is legitimate vocabulary
            % inside +crit and screening on it is a false positive. The two
            % quantities sharing one English word is a genuine terminology
            % collision --.
            critDir = fullfile(fileparts(which("rid.defaultOptions")), "+crit");
            files   = dir(fullfile(critDir, "*.m"));
            tc.assertNotEmpty(files, "no +crit sources found; test is vacuous");
            for iFile = 1:numel(files)
                src = string(fileread(fullfile(files(iFile).folder, ...
                                               files(iFile).name)));
                for forbidden = ["rid.gen.", "violationScale", "tailWeight", ...
                                 "Constraints", "admissible", "gradPen"]
                    tc.verifyFalse(contains(src, forbidden), ...
                        files(iFile).name + " references " + forbidden + ...
                        " -- +crit must never see a constraint.");
                end
            end
        end

        function psiMaxIsReadFromCritAndIsNotADuplicateUnderGen(tc)
            % Fails if: psiMax is hard-coded, or a second copy appears in opts.gen
            % where it could drift away from the criterion's.
            tc.verifyFalse(isfield(rid.defaultOptions().gen, "psiMax"));
            gen = PenaltyTest.makeGen([-1 1], 8);
            Zphys   = PenaltyTest.constant(8, 1.5);
            tc.verifyEqual(gen.penalty(Zphys, "psiMax", 2) / gen.penalty(Zphys, "psiMax", 1), ...
                2, "RelTol", 1e-12);
        end

        % --- shape and edge cases -------------------------------------------------

        function aHorizonMismatchIsAnError(tc)
            gen = PenaltyTest.makeGen([-1 1], 6);
            tc.verifyError(@() gen.penalty(zeros(5, 3)), "rid:gen:horizonMismatch");
            tc.verifyError(@() gen.penalty(zeros(7, 3)), "rid:gen:horizonMismatch");
        end

        function aPredictionOfTheWrongWidthIsAnError(tc)
            gen = PenaltyTest.makeGen([-1 1], 6);
            tc.verifyError(@() gen.penalty(zeros(6, 2)), "rid:gen:invalidPrediction");
        end

        function aRepresentationWithNoSoftConstraintsCostsNothing(tc)
            % Fails if: the loop over an empty soft array produces NaN or errors.
            cons = rid.gen.Constraints(rid.rep.Narx(2, 0, "inputDifference", true), ...
                       struct("u1_k", [-2 3], "du1_k", [-0.4 0.4]));
            gen  = rid.gen.Direct(cons, 5);
            [pen, gradPen, info] = gen.penalty(zeros(5, 2));
            tc.verifyEqual(pen, 0);
            tc.verifyEqual(gradPen, zeros(5, 2));
            tc.verifyEqual(info.nActive, 0);
        end

        function infoReportsTheWeightTheProfileAndTheUnweightedCost(tc)
            gen = PenaltyTest.makeGen([-1 1], 20);
            [pen, ~, info] = gen.penalty( ...
                PenaltyTest.uniform(20, 0.05, 0, 1), ...
                "violationScale", 0.05, "tailWeight", 0.1, "psiMax", 1);
            tc.verifyEqual(info.w, 400, "RelTol", 1e-12);
            tc.verifyEqual(mean(info.gamma), 1, "AbsTol", 1e-14);
            tc.verifyEqual(info.name, "y_km1");
            tc.verifyEqual(info.nActive, 1);
            % The run record logs J and the penalty separately, so the unweighted
            % cost must be recoverable from what is returned.
            tc.verifyEqual(info.w * info.p, pen, "AbsTol", 1e-12);
        end

        function isPureAndRepeatable(tc)
            gen = PenaltyTest.makeGen([-1 1], 6);
            Zphys   = PenaltyTest.constant(6, 1.4);
            [p1, g1] = gen.penalty(Zphys);
            [p2, g2] = gen.penalty(Zphys);
            tc.verifyEqual(p1, p2);
            tc.verifyEqual(g1, g2);
        end

    end

    methods (Static, Access = private)

        function generator = makeGen(outputBox, nHorizon)
            %MAKEGEN  A Direct whose only soft constraint is y_km1 over `outputBox`.
            cons = rid.gen.Constraints(rid.rep.Narx(2, 1), ...
                       struct("u1_k", [-2 3], "du1_k", [-0.4 0.4], ...
                              "y_km1", outputBox));
            generator = rid.gen.Direct(cons, nHorizon);
        end

        function Zphys = constant(nHorizon, g)
            %CONSTANT  y_km1 held at `g` for the whole horizon.
            Zphys = zeros(nHorizon, 3);
            Zphys(:, 3) = g;
        end

        function Zphys = uniform(nHorizon, v, gMid, gHalf)
            %UNIFORM  y_km1 sitting a fraction `v` of the admissible width outside
            %   its limit, at every horizon step. s = 2*gHalf.
            Zphys = PenaltyTest.constant(nHorizon, gMid + gHalf + v * 2 * gHalf);
        end

        function Zphys = atStep(nHorizon, jStep, v, gMid, gHalf)
            %ATSTEP  The same violation, at one horizon step only.
            Zphys = PenaltyTest.constant(nHorizon, gMid);
            Zphys(jStep, 3) = gMid + gHalf + v * 2 * gHalf;
        end

    end

end
