classdef ConstraintsTest < matlab.unittest.TestCase
%CONSTRAINTSTEST  Classification, the default and the contradictions.
%
%   Layers 1 and 2 of the project's test plan for rid.gen.Constraints. The load-bearing tests are
%   the CLASSIFICATION ones: whether a coordinate is hard or soft decides whether
%   the optimizer is bounded by a declaration or merely charged for crossing it, and
%   a misclassification produces no error at all -- the run simply designs a signal
%   the actuator cannot execute, and the regressor points land somewhere other than
%   where the criterion believed it was placing them.
%
%   The expected classifications are written out by hand, never generated by the code under
%   test. Boxes are deliberately asymmetric and away from the origin so that a
%   normalization, a sign slip or a midpoint/half-width confusion cannot pass.
%
%   Two of these tests are regressions for defects that the coordinate-meaning rule made unrepresentable:
%   `nk > 0` pushing an input level past the old lag bound, and a channel count
%   held in two places. Both classified an input decision variable as SOFT, and
%   neither raised anything. They are kept as the reproductions that forced the
%   interface change.

    properties (Constant)
        Tol = 1e-12
    end

    methods (Test)

        % --- what the declaration becomes ------------------------------------

        function theDeclarationIsStoredVerbatimAndInCoordinateOrder(tc)
            % the admissible region is a lookup of declared numbers, in the
            % representation's own coordinate order. Nothing is derived, reordered
            % or rescaled on the way in.
            rep   = rid.rep.Narx(2, 1);
            adm   = ConstraintsTest.declare(rep.requiredNames(), struct( ...
                        "u1_k", [100 220], "du1_k", [-4 7], "y_km1", [-30 50]));
            cons  = rid.gen.Constraints(rep, adm);

            tc.verifyEqual(cons.dimName, rep.requiredNames());
            tc.verifyEqual(cons.nDim, rep.nDim);
            tc.verifyEqual(cons.admissibleBox, [100 220; -4 7; -30 50], ...
                "AbsTol", tc.Tol);
        end

        function amplitudeIsThePhysicalDeclarationNotANormalizedOne(tc)
            % +gen works in PHYSICAL units; normalization happens at the
            % representation boundary. A box far from the origin and far from unit
            % width catches a stray normalization in either direction.
            rep  = rid.rep.Narx(2, 1);
            adm  = ConstraintsTest.declare(rep.requiredNames(), ...
                       struct("u1_k", [100 220]));
            cons = rid.gen.Constraints(rep, adm);

            tc.verifyEqual(cons.amplitude, [100 220], "AbsTol", tc.Tol);
            tc.verifyEqual(cons.levelDim, 1);
            tc.verifyEqual(cons.dimName(cons.levelDim), "u1_k");
            tc.verifyEqual(cons.channelName, "u1");
        end

        % --- classification ------------------------------------------

        function simulatedCoordinatesAreSoftAndCarryMidpointAndHalfWidth(tc)
            % The penalty is written around (gMid, gHalf) rather than (lo, hi), so
            % a midpoint/half-width confusion is silent in every aggregate check.
            rep  = rid.rep.Narx(2, 1);
            adm  = ConstraintsTest.declare(rep.requiredNames(), ...
                       struct("y_km1", [-30 50]));
            cons = rid.gen.Constraints(rep, adm);

            tc.verifyEqual(numel(cons.soft), 1);
            tc.verifyEqual(cons.soft(1).name, "y_km1");
            tc.verifyEqual(cons.soft(1).iDim, 3);
            tc.verifyEqual(cons.soft(1).gMid, 10, "AbsTol", tc.Tol);
            tc.verifyEqual(cons.soft(1).gHalf, 40, "AbsTol", tc.Tol);
            tc.verifyEqual(cons.soft(1).s, 80, "AbsTol", tc.Tol);
        end

        function eachChannelGetsItsOwnAmplitudeAndRate(tc)
            % Per-input ranges in the multivariate case.
            %   Distinct boxes per channel
            % catch a channel/lag index swap.
            rep = rid.rep.Narx(2, 1, "nInputs", 2);
            tc.verifyEqual(rep.requiredNames(), ...
                ["u1_k" "du1_k" "u2_k" "du2_k" "y_km1"]);

            adm  = ConstraintsTest.declare(rep.requiredNames(), struct( ...
                       "u1_k", [-2 3], "du1_k", [-0.5 0.5], ...
                       "u2_k", [10 40], "du2_k", [-7 2], "y_km1", [-10 10]));
            cons = rid.gen.Constraints(rep, adm);

            tc.verifyEqual(cons.channelName, ["u1" "u2"]);
            tc.verifyEqual(cons.amplitude, [-2 3; 10 40], "AbsTol", tc.Tol);
            tc.verifyEqual(cons.rate, [-0.5 0.5; -7 2], "AbsTol", tc.Tol);
            tc.verifyEqual(cons.levelDim, [1 3]);
            tc.verifyEqual([cons.soft.name], "y_km1");
        end

        % --- the default rate limit ----------------------------------

        function theDefaultRateLimitIsTheDeclaredDuBound(tc)
            rep  = rid.rep.Narx(2, 1);
            adm  = ConstraintsTest.declare(rep.requiredNames(), ...
                       struct("du1_k", [-0.5 0.4]));
            cons = rid.gen.Constraints(rep, adm);

            tc.verifyEqual(cons.rate, [-0.5 0.4], "AbsTol", tc.Tol);
            tc.verifyEqual(cons.rateSource, "duCoordinate");
            tc.verifyFalse(cons.rateIsDeclared);
        end

        function withoutADuCoordinateTheDefaultIsTheAmplitudeWidth(tc)
            % +-(uMax - uMin): non-binding, and that is the knowingly accepted
            % consequence recorded.
            rep = rid.rep.Narx(3, 1, "inputDifference", false);
            tc.verifyEqual(rep.requiredNames(), ...
                ["u1_k" "u1_km1" "u1_km2" "y_km1"]);

            adm  = ConstraintsTest.declare(rep.requiredNames(), struct( ...
                       "u1_k", [-2 3], "u1_km1", [-2 3], "u1_km2", [-2 3]));
            cons = rid.gen.Constraints(rep, adm);

            tc.verifyEqual(cons.rate, [-5 5], "AbsTol", tc.Tol);
            tc.verifyEqual(cons.rateSource, "amplitudeWidth");
            tc.verifyFalse(cons.rateIsDeclared);
        end

        function theDefaultRateLimitIsAlwaysFinite(tc)
            % The reason the default is not [-inf, inf]: an infinity propagates
            % into the random-walk construction of the warm-start initialization and makes the rate
            % consistency check vacuous.
            reps = {rid.rep.Narx(2, 1), ...
                    rid.rep.Narx(3, 1, "inputDifference", false), ...
                    rid.rep.Narx(2, 1, "nInputs", 2), ...
                    rid.rep.Narx(2, 0, "nk", 2, "inputDifference", false)};
            for iRep = 1:numel(reps)
                cons = rid.gen.Constraints(reps{iRep}, ...
                    ConstraintsTest.declare(reps{iRep}.requiredNames()));
                tc.verifyTrue(all(isfinite(cons.rate), "all"), ...
                    "The default rate limit must be finite.");
                tc.verifyTrue(all(cons.rate(:,1) <= 0 & cons.rate(:,2) >= 0));
            end
        end

        function aDeclaredRateLimitOverridesTheDefault(tc)
            % The rate limit is part of the DECLARATION, passed here, never read
            % from an options struct.
            rep  = rid.rep.Narx(2, 1);
            adm  = ConstraintsTest.declare(rep.requiredNames(), ...
                       struct("du1_k", [-0.5 0.5]));
            cons = rid.gen.Constraints(rep, adm, ...
                       "rateLimit", struct("u1", [-0.1 0.2]));

            tc.verifyEqual(cons.rate, [-0.1 0.2], "AbsTol", tc.Tol);
            tc.verifyEqual(cons.rateSource, "declared");
            tc.verifyTrue(cons.rateIsDeclared);
        end

        function theRateLimitIsNotTakenFromDefaultOptions(tc)
            % Guards the seam from the other side: rid.defaultOptions carries no
            % rate limit, so nothing can quietly start supplying one.
            tc.verifyFalse(isfield(rid.defaultOptions().gen, "rateLimit"));
        end

        % --- contradictory declarations ------------------------------

        function contradictoryAmplitudeLagsAreAnErrorNotAnIntersection(tc)
            % u1_k and u1_km1 are the same actuator at two instants. Taking one, or
            % their intersection, would be the silent acceptance the project's coding standard forbids.
            rep = rid.rep.Narx(3, 1, "inputDifference", false);
            adm = ConstraintsTest.declare(rep.requiredNames(), struct( ...
                      "u1_k", [-2 3], "u1_km1", [-1 1], "u1_km2", [-2 3]));

            tc.verifyError(@() rid.gen.Constraints(rep, adm), ...
                "rid:gen:inconsistentAmplitude");
            msg = ConstraintsTest.messageOf(@() rid.gen.Constraints(rep, adm));
            tc.verifySubstring(msg, 'u1_k');
            tc.verifySubstring(msg, 'u1_km1');
        end

        function contradictoryRateLagsAreAnError(tc)
            rep = rid.rep.Narx(3, 1, "inputDifference", true);
            adm = ConstraintsTest.declare(rep.requiredNames(), struct( ...
                      "du1_k", [-0.5 0.5], "du1_km1", [-0.6 0.6]));

            tc.verifyError(@() rid.gen.Constraints(rep, adm), ...
                "rid:gen:inconsistentRate");
            msg = ConstraintsTest.messageOf(@() rid.gen.Constraints(rep, adm));
            tc.verifySubstring(msg, 'du1_k');
            tc.verifySubstring(msg, 'du1_km1');
        end

        function agreeingLagsAreNotAContradiction(tc)
            rep  = rid.rep.Narx(3, 1, "inputDifference", true);
            adm  = ConstraintsTest.declare(rep.requiredNames(), struct( ...
                       "du1_k", [-0.5 0.5], "du1_km1", [-0.5 0.5]));
            cons = rid.gen.Constraints(rep, adm);
            tc.verifyEqual(cons.rate, [-0.5 0.5], "AbsTol", tc.Tol);
        end

        % --- an undeclarable admissible region -------------------------------

        function anUnboundedAdmissibleBoundIsAnError(tc)
            % The admissible region is a declared specification. rid.rep.bounds
            % checks only shape, so this invariant is owned here.
            rep = rid.rep.Narx(2, 1);
            adm = ConstraintsTest.declare(rep.requiredNames(), ...
                      struct("y_km1", [-Inf Inf]));
            tc.verifyError(@() rid.gen.Constraints(rep, adm), ...
                "rid:gen:invalidAdmissibleBox");
            tc.verifySubstring( ...
                ConstraintsTest.messageOf(@() rid.gen.Constraints(rep, adm)), ...
                'y_km1');
        end

        function anInvertedOrDegenerateAdmissibleBoundIsAnError(tc)
            rep = rid.rep.Narx(2, 1);
            for bad = {[3 -2], [1 1]}
                adm = ConstraintsTest.declare(rep.requiredNames(), ...
                          struct("u1_k", bad{1}));
                tc.verifyError(@() rid.gen.Constraints(rep, adm), ...
                    "rid:gen:invalidAdmissibleBox");
            end
        end

        % --- an undeclarable rate limit --------------------------------------

        function aRateLimitExcludingZeroIsAnError(tc)
            % Holding the input constant would be infeasible, and the warm
            % start -- which repeats the last sample -- would need repair.
            rep = rid.rep.Narx(2, 1);
            adm = ConstraintsTest.declare(rep.requiredNames());

            tc.verifyError(@() rid.gen.Constraints(rep, adm, ...
                "rateLimit", struct("u1", [0.1 0.2])), "rid:gen:invalidRateLimit");
            msg = ConstraintsTest.messageOf(@() rid.gen.Constraints(rep, adm, ...
                "rateLimit", struct("u1", [0.1 0.2])));
            tc.verifySubstring(msg, 'zero increment');
        end

        function aDuCoordinateExcludingZeroIsAlsoAnError(tc)
            % Same invariant, reached through the default rather than through
            % an explicit rate limit.
            rep = rid.rep.Narx(2, 1);
            adm = ConstraintsTest.declare(rep.requiredNames(), ...
                      struct("du1_k", [0.1 0.2]));
            tc.verifyError(@() rid.gen.Constraints(rep, adm), ...
                "rid:gen:invalidRateLimit");
        end

        function aMalformedRateLimitIsAnError(tc)
            rep = rid.rep.Narx(2, 1);
            adm = ConstraintsTest.declare(rep.requiredNames());
            for bad = {0.5, [1 2 3], [0.5 -0.5], [-Inf 1], "wide", [1 2; 3 4]}
                tc.verifyError(@() rid.gen.Constraints(rep, adm, ...
                    "rateLimit", struct("u1", bad(1))), ...
                    "rid:gen:invalidRateLimit");
            end
        end

        function anUnknownChannelInTheRateLimitIsAnError(tc)
            % A typo is not a no-op: a rate limit nobody applied is worse than none.
            rep = rid.rep.Narx(2, 1);
            adm = ConstraintsTest.declare(rep.requiredNames());
            tc.verifyError(@() rid.gen.Constraints(rep, adm, ...
                "rateLimit", struct("u2", [-1 1])), "rid:gen:unknownRateLimit");
        end

        function aChannelWithoutALevelCoordinateIsAnError(tc)
            % A channel with a rate but no level: its amplitude limit cannot be
            % declared. Unreachable through Narx, hence the double -- which also
            % demonstrates that +gen consumes the INTERFACE and not rid.rep.Narx.
            rep = StubRepresentation( ...
                {"du1_k", "inputDifference", 1, 0}, ...
                {"y_km1", "output",        NaN, 1});
            adm = ConstraintsTest.declare(rep.requiredNames());
            tc.verifyError(@() rid.gen.Constraints(rep, adm), ...
                "rid:gen:missingAmplitude");
        end

        function aRepresentationWithNoInputCoordinateIsAnError(tc)
            rep = StubRepresentation({"y_km1", "output", NaN, 1});
            adm = ConstraintsTest.declare(rep.requiredNames());
            tc.verifyError(@() rid.gen.Constraints(rep, adm), ...
                "rid:gen:missingAmplitude");
        end

        % --- regressions for the two defects the coordinate-meaning rule removed --------------------

        function anInputLevelPastTheOldLagBoundIsStillHard(tc)
            % REGRESSION. With nk = 2 and nLagY = 0 the coordinates are
            % [u1_km2, u1_km3] and nDim = 2, so the old lag search 0:nDim found
            % u1_km2 and missed u1_km3. u1_km3 -- an input level, a decision
            % variable -- was then classified SOFT and merely penalized, silently.
            rep = rid.rep.Narx(2, 0, "nk", 2, "inputDifference", false);
            tc.verifyEqual(rep.requiredNames(), ["u1_km2" "u1_km3"]);

            cons = rid.gen.Constraints(rep, ...
                       ConstraintsTest.declare(rep.requiredNames()));
            tc.verifyEmpty(cons.soft);
            tc.verifyEqual(cons.amplitude, [-2 3], "AbsTol", tc.Tol);
            tc.verifyEqual(cons.levelDim, 1);          % the smallest lag, u1_km2
        end

        function theContradictionCheckSurvivesPastTheOldLagBound(tc)
            % REGRESSION. The same defect silently disabled the admissible-region declaration: with only one
            % level index found, assertOneBox had nothing to compare, so declaring
            % u1_km2 and u1_km3 over different boxes was ACCEPTED.
            rep = rid.rep.Narx(2, 0, "nk", 2, "inputDifference", false);
            adm = ConstraintsTest.declare(rep.requiredNames(), ...
                      struct("u1_km3", [-99 99]));
            tc.verifyError(@() rid.gen.Constraints(rep, adm), ...
                "rid:gen:inconsistentAmplitude");
        end

        function everyInputChannelIsConstrainedWithoutBeingCounted(tc)
            % REGRESSION. nInputs used to be a Constraints option defaulting to
            % opts.rep.nInputs, so a two-input representation with the default
            % silently made u2_k and du2_k SOFT: channel 2 kept no rate limit and
            % could leave its box for a penalty. The count is now read from the
            % representation and cannot disagree.
            rep = rid.rep.Narx(2, 1, "nInputs", 2);
            cons = rid.gen.Constraints(rep, ...
                       ConstraintsTest.declare(rep.requiredNames()));

            tc.verifyEqual(cons.channelName, ["u1" "u2"]);
            tc.verifyEqual([cons.soft.name], "y_km1");   % and NOT u2_k / du2_k
            tc.verifyEqual(size(cons.amplitude), [2 2]);
            tc.verifyEqual(size(cons.rate), [2 2]);
        end

        function theChannelCountIsNotAnOption(tc)
            % Guards the seam from the other side: there is no way to tell
            % Constraints a different p from the one its representation has.
            rep = rid.rep.Narx(2, 1);
            adm = ConstraintsTest.declare(rep.requiredNames());
            tc.verifyError(@() rid.gen.Constraints(rep, adm, "nInputs", 2), ...
                "MATLAB:TooManyInputs");
            tc.verifySubstring(ConstraintsTest.messageOf( ...
                @() rid.gen.Constraints(rep, adm, "nInputs", 2)), 'nInputs');
        end

        function anOutputDifferenceIsSoftLikeAnOutput(tc)
            % The coordinate-meaning rule, the four-kinds question made concrete. rid.rep.Narx cannot
            % emit an output difference at all -- its difference basis applies to
            % inputs only -- so `dy` reaches the classifier solely through the
            % interface, where it must be declared "output". That is the correct
            % answer, not a gap: the row for `dy` says soft, and soft is what
            % it gets. This is why no fifth kind is needed.
            rep  = StubRepresentation( ...
                {"u1_k",   "inputLevel", 1, 0}, ...
                {"y_km1",  "output",   NaN, 1}, ...
                {"dy_km1", "output",   NaN, 1});
            cons = rid.gen.Constraints(rep, ...
                       ConstraintsTest.declare(rep.requiredNames()));

            tc.verifyEqual(sort([cons.soft.name]), ["dy_km1" "y_km1"]);
            tc.verifyEqual(cons.channelName, "u1");
        end

        function classificationIsAKindSwitchNotANameMatch(tc)
            % A representation whose names follow no convention at all must
            % still classify correctly, because only .kind is consulted.
            rep  = StubRepresentation( ...
                {"throttle",      "inputLevel",      1, 0}, ...
                {"throttleDelta", "inputDifference", 1, 0}, ...
                {"exhaustTemp",   "output",        NaN, 1});
            cons = rid.gen.Constraints(rep, ConstraintsTest.declare( ...
                       rep.requiredNames(), struct("throttleDelta", [-0.5 0.5])));

            tc.verifyEqual([cons.soft.name], "exhaustTemp");
            tc.verifyEqual(cons.rate, [-0.5 0.5], "AbsTol", tc.Tol);
            tc.verifyEqual(cons.rateSource, "duCoordinate");
        end

        % --- reporting --------------------------------------------------------

        function describeNamesEveryChannelItsRateSourceAndTheSoftCoordinates(tc)
            rep  = rid.rep.Narx(2, 1);
            cons = rid.gen.Constraints(rep, ...
                       ConstraintsTest.declare(rep.requiredNames()));
            s = cons.describe();

            tc.verifyClass(s, "string");
            tc.verifySubstring(s, 'u1');
            tc.verifySubstring(s, 'duCoordinate');
            tc.verifySubstring(s, 'y_km1');
        end

        function describeSaysNoneWhenNothingIsSoft(tc)
            rep  = rid.rep.Narx(2, 0, "inputDifference", true);
            cons = rid.gen.Constraints(rep, ...
                       ConstraintsTest.declare(rep.requiredNames()));
            tc.verifySubstring(cons.describe(), '(none)');
        end

        function constructionIsPureAndRepeatable(tc)
            rep = rid.rep.Narx(2, 1);
            adm = ConstraintsTest.declare(rep.requiredNames());
            a = rid.gen.Constraints(rep, adm);
            b = rid.gen.Constraints(rep, adm);
            tc.verifyEqual(a.amplitude, b.amplitude);
            tc.verifyEqual(a.rate, b.rate);
            tc.verifyEqual(a.describe(), b.describe());
        end

    end

    methods (Static, Access = private)

        function adm = declare(names, overrides)
            %DECLARE  A valid admissible declaration, with per-name overrides.
            %
            %   Defaults are asymmetric and of non-unit width so that a test which
            %   does not override a coordinate still cannot pass by symmetry.
            arguments
                names     (1,:) string
                overrides (1,1) struct = struct()
            end
            adm = struct();
            for iName = 1:numel(names)
                adm.(names(iName)) = [-2 3];
            end
            given = string(fieldnames(overrides)).';
            for iGiven = 1:numel(given)
                adm.(given(iGiven)) = overrides.(given(iGiven));
            end
        end

        function msg = messageOf(fh)
            %MESSAGEOF  The message of the error `fh` raises, as a char row.
            try
                fh();
                msg = '';
            catch err
                msg = err.message;
            end
        end

    end

end
