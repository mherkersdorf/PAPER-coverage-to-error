classdef DirectTest < matlab.unittest.TestCase
%DIRECTTEST  Parametrization and feasible set for rid.gen.Direct.
%
%   The load-bearing test is `theFeasibleSetIsExactlyTheTrajectoryConstraintSet`:
%   everything else here checks a piece, that one checks the claim the optimizer
%   actually relies on -- that `lb`, `ub`, `A`, `b` describe the SAME set as "the
%   trajectory respects the amplitude and rate limits". If the description is looser
%   than the truth the optimizer returns signals the actuator cannot execute; if it
%   is tighter, the search is silently restricted and no error ever appears.
%
%   It is written as an equivalence over random points and asserts that BOTH classes
%   occur, because a membership test on a sample that happens to be all-members or
%   all-non-members passes without testing anything.
%
%   Expected layouts are written out by hand, never generated by the code under test.

    properties (Constant)
        Tol = 1e-12
    end

    methods (Test)

        % --- the parametrization ---------------------------------------------

        function nParamsIsHorizonTimesChannels(tc)
            tc.verifyEqual(DirectTest.siso(5).nParams(), 5);
            tc.verifyEqual(DirectTest.miso(4).nParams(), 8);
        end

        function nParamsTakesNoHorizonArgument(tc)
            % nHorizon lives on the object. A parameter here would be a
            % second source of one number that could disagree with the first.
            gen = DirectTest.siso(5);
            tc.verifyError(@() gen.nParams(7), "MATLAB:TooManyInputs");
        end

        function theHorizonHasNoDefaultAnywhere(tc)
            % The nHorizon ownership rule mirrors the required epsReq0: a consequential user choice is not given a
            % default, and the absence is asserted so it cannot drift back in.
            tc.verifyFalse(isfield(rid.defaultOptions().gen, "nHorizon"));
            tc.verifyError(@() rid.gen.Direct(DirectTest.constraints(1)), ...
                "MATLAB:minrhs");
        end

        function toTrajectoryIsChannelMajor(tc)
            % The ordering section 3's kron blocking assumes: each channel owns a
            % contiguous block of nHorizon entries.
            gen   = DirectTest.miso(3);
            theta = [1; 2; 3; 40; 50; 60];
            tc.verifyEqual(gen.toTrajectory(theta), [1 40; 2 50; 3 60], ...
                "AbsTol", tc.Tol);
        end

        function toTrajectoryRejectsAMisSizedVector(tc)
            gen = DirectTest.siso(5);
            tc.verifyError(@() gen.toTrajectory((1:4).'), "rid:gen:invalidTheta");
            tc.verifyError(@() gen.toTrajectory((1:6).'), "rid:gen:invalidTheta");
        end

        function theAppliedUnitIsOneSample(tc)
            % the applied unit is defined by the PARAMETRIZATION. For Direct
            % it is one sample, and +rhc commits exactly this.
            gen  = DirectTest.miso(3);
            uSeq = gen.toTrajectory([1; 2; 3; 40; 50; 60]);
            tc.verifyEqual(gen.applied(uSeq), [1 40], "AbsTol", tc.Tol);
            tc.verifyEqual(size(gen.applied(uSeq)), [1 2]);
        end

        function appliedRejectsAMisShapedTrajectory(tc)
            gen = DirectTest.siso(5);
            tc.verifyError(@() gen.applied(zeros(4, 1)), "rid:gen:invalidTrajectory");
            tc.verifyError(@() gen.applied(zeros(5, 2)), "rid:gen:invalidTrajectory");
        end

        % --- the warm start ---------------------------------------------------

        function shiftDropsTheAppliedSampleAndRepeatsTheLast(tc)
            gen = DirectTest.miso(3);
            tc.verifyEqual(gen.shift([1; 2; 3; 40; 50; 60]), ...
                [2; 3; 3; 50; 60; 60], "AbsTol", tc.Tol);
        end

        function theWarmStartOfAFeasibleSolutionNeedsNoRepair(tc)
            % The warm-start initialization, the property the whole multi-start scheme rests on. The applied
            % input becomes u(k-1) of the next step, which is what makes the new
            % first variable's bound the previous solution's own first interior
            % constraint.
            gen  = DirectTest.siso(6);
            hist = wellFormedHistory(0.3);

            [lb, ub, A, b] = gen.feasibleSet(hist);
            theta = DirectTest.rateFeasibleWalk(gen, hist, ...
                        RandStream("twister", "Seed", 42));
            tc.assertTrue(DirectTest.isMember(theta, lb, ub, A, b), ...
                "fixture is not feasible; the test below would prove nothing");

            uSeq  = gen.toTrajectory(theta);
            next  = wellFormedHistory([hist.u; gen.applied(uSeq)]);
            [lb2, ub2, A2, b2] = gen.feasibleSet(next);
            tc.verifyTrue(DirectTest.isMember(gen.shift(theta), lb2, ub2, A2, b2));
        end

        % --- initialization and multi-start ---------------------------

        function theWarmStartOfAFeasibleSolutionNeedsNoRepairAtTheRateBoundary(tc)
            % The sharpened form of the property. The previous solution's last
            % TWO samples sit a full rate step apart, so extending it by anything
            % other than REPEATING the last sample is infeasible; and it is
            % non-constant throughout, so `shift` is not the identity. Both matter:
            % a constant thetaPrev would pass on an implementation that ignored it.
            %
            % Fails if: shift extends by extrapolation, or drops the wrong end.
            gen  = DirectTest.siso(5);            % amplitude [-2 3], rate [-0.4 0.4]
            hist = wellFormedHistory(0.3);
            uSeq = [0.3; 0.7; 0.4; 0.8; 1.2];     % every step exactly +-0.4 or less
            tc.assertEqual(abs(uSeq(end) - uSeq(end-1)), 0.4, "AbsTol", tc.Tol, ...
                "fixture must end at the rate boundary or the test is weaker");
            tc.assertGreaterThan(numel(unique(uSeq)), 1, "fixture must be non-constant");
            theta = uSeq(:);

            [lb, ub, A, b] = gen.feasibleSet(hist);
            tc.assertTrue(DirectTest.isMember(theta, lb, ub, A, b));

            next = wellFormedHistory([hist.u; gen.applied(gen.toTrajectory(theta))]);
            [lb2, ub2, A2, b2] = gen.feasibleSet(next);
            shifted = gen.shift(theta);
            tc.verifyTrue(DirectTest.isMember(shifted, lb2, ub2, A2, b2));
            tc.verifyEqual(shifted, [0.7; 0.4; 0.8; 1.2; 1.2], "AbsTol", tc.Tol);
        end

        function rowOneIsTheWarmStartAndTheRestAreNot(tc)
            % Fails if: the warm start is placed anywhere but row 1, or the walks
            % happen to start from thetaPrev rather than from u(k-1).
            gen   = DirectTest.siso(5);
            hist  = wellFormedHistory(0.3);
            theta = [0.3; 0.7; 0.4; 0.8; 1.2];
            Theta0 = gen.initialGuesses(hist, theta, "nStarts", 4);

            tc.verifyEqual(size(Theta0), [4, gen.nParams()]);
            tc.verifyEqual(Theta0(1, :).', gen.shift(theta), "AbsTol", tc.Tol);
            for iStart = 2:4
                tc.verifyNotEqual(Theta0(iStart, :), Theta0(1, :));
            end
        end

        function everyStartIsFeasibleIncludingUnderAnAsymmetricRateLimit(tc)
            % The warm-start initialization's guarantee, over a sweep of seeds. The asymmetric rate box is
            % the case that breaks a reflecting construction: reflecting u + duMax
            % about uMax gives a step near -duMax, which duMin forbids.
            %
            % Fails if: increments are drawn from the full rate box and then
            % reflected at the amplitude wall -- measured, all 60 seeds violate.
            cons = rid.gen.Constraints(rid.rep.Narx(2, 1), ...
                       DirectTest.declare(["u1_k" "du1_k" "y_km1"], ...
                           struct("u1_k", [-2 3], "du1_k", [-0.1 0.6])));
            gen  = rid.gen.Direct(cons, 8);
            hist = wellFormedHistory(2.9);              % hard against uMax = 3
            [lb, ub, A, b] = gen.feasibleSet(hist);
            for seed = 1:20
                Theta0 = gen.initialGuesses(hist, zeros(0, 1), ...
                             "nStarts", 4, "seed", seed);
                for iStart = 1:4
                    tc.verifyTrue( ...
                        DirectTest.isMember(Theta0(iStart, :).', lb, ub, A, b), ...
                        sprintf("seed %d, start %d infeasible", seed, iStart));
                end
            end
        end

        function targetSequencesAreFeasibleWhereIidDrawsAreNot(tc)
            % Fails if: the starts are i.i.d. uniform over the amplitude box. The
            % mutant is computed here so the contrast is asserted rather than
            % assumed -- without it this test passes on any construction at all.
            gen  = DirectTest.siso(10);           % rate [-0.4 0.4], box [-2 3]
            hist = wellFormedHistory(0.3);
            [lb, ub, A, b] = gen.feasibleSet(hist);

            Theta0 = gen.initialGuesses(hist, zeros(0, 1), "nStarts", 4, "seed", 3);
            for iStart = 2:4
                tc.verifyTrue(DirectTest.isMember(Theta0(iStart, :).', lb, ub, A, b));
            end

            stream = RandStream("twister", "Seed", 3);
            nIidFeasible = 0;
            for iDraw = 1:50
                iid = lb + (ub - lb) .* rand(stream, size(lb));
                nIidFeasible = nIidFeasible + DirectTest.isMember(iid, lb, ub, A, b);
            end
            tc.verifyEqual(nIidFeasible, 0, ...
                "i.i.d. draws must be rate-infeasible or the contrast is empty");
        end

        function startsAreReproducibleFromTheirSeedAndDifferAcrossSeeds(tc)
            % Both halves are needed: without the second, a constant implementation
            % passes the first.
            gen  = DirectTest.siso(6);
            hist = wellFormedHistory(0.3);
            a = gen.initialGuesses(hist, zeros(0, 1), "nStarts", 4, "seed", 11);
            b = gen.initialGuesses(hist, zeros(0, 1), "nStarts", 4, "seed", 11);
            c = gen.initialGuesses(hist, zeros(0, 1), "nStarts", 4, "seed", 12);
            tc.verifyEqual(a, b);
            tc.verifyNotEqual(a(2:end, :), c(2:end, :));
        end

        function theGlobalStreamIsNeverTouched(tc)
            % Fails if the implementation calls rand() without a stream.
            gen = DirectTest.siso(6);
            before = RandStream.getGlobalStream().State;
            gen.initialGuesses(wellFormedHistory(0.3), zeros(0, 1), "nStarts", 4, "seed", 5);
            tc.verifyEqual(RandStream.getGlobalStream().State, before);
        end

        function aRandStreamMayBePassedInsteadOfASeed(tc)
            % The opts.roi.seed precedent: the argument is a seed OR a RandStream.
            gen  = DirectTest.siso(6);
            hist = wellFormedHistory(0.3);
            tc.verifyEqual( ...
                gen.initialGuesses(hist, zeros(0, 1), "nStarts", 4, ...
                    "seed", RandStream("twister", "Seed", 9)), ...
                gen.initialGuesses(hist, zeros(0, 1), "nStarts", 4, "seed", 9));
        end

        function eachChannelIsBuiltInsideItsOwnLimits(tc)
            % Fails if: a scalar rate or amplitude is broadcast across channels.
            cons = rid.gen.Constraints(rid.rep.Narx(2, 1, "nInputs", 2), ...
                       DirectTest.declare(["u1_k" "du1_k" "u2_k" "du2_k" "y_km1"], ...
                           struct("u1_k", [-2 3],  "du1_k", [-0.4 0.4], ...
                                  "u2_k", [10 40], "du2_k", [-7 2])));
            gen  = rid.gen.Direct(cons, 12);
            hist = wellFormedHistory([0 20]);
            Theta0 = gen.initialGuesses(hist, zeros(0, 1), "nStarts", 5, "seed", 4);

            for iStart = 2:5
                uSeq = gen.toTrajectory(Theta0(iStart, :).');
                for cIn = 1:2
                    u  = uSeq(:, cIn);
                    du = [u(1) - hist.u(cIn); diff(u)];
                    tc.verifyGreaterThanOrEqual(u,  cons.amplitude(cIn,1) - tc.Tol);
                    tc.verifyLessThanOrEqual(u,     cons.amplitude(cIn,2) + tc.Tol);
                    tc.verifyGreaterThanOrEqual(du, cons.rate(cIn,1) - tc.Tol);
                    tc.verifyLessThanOrEqual(du,    cons.rate(cIn,2) + tc.Tol);
                end
                % ... and the two channels must not be in the same place.
                tc.verifyGreaterThan(abs(mean(uSeq(:,2)) - mean(uSeq(:,1))), 1);
            end
        end

        function infoCarriesTheSeedAndTheStartProvenance(tc)
            % the run record must be able to say how these starts were made.
            gen = DirectTest.siso(6);
            [~, info] = gen.initialGuesses(wellFormedHistory(0.3), zeros(0, 1), ...
                            "nStarts", 4, "seed", 7);
            tc.verifyEqual(info.seed, 7);
            tc.verifyEqual(info.nStarts, 4);
            tc.verifyEqual(info.nSequences, 4);
            tc.verifyEqual(info.warmStart, "none");
            tc.verifyEqual(info.targetRange, "amplitudeBox");   % no roiInputRange given
            tc.verifyEqual(info.guided, false(1, 4));           % no targetLevels given
        end

        function theRateLimitIsAlwaysFiniteSoNoIidFallbackIsReachable(tc)
            % Reported rather than implemented: the i.i.d.-over-the-box fallback for
            % "no rate limit" is DEAD CODE, because rid.gen.Constraints cannot
            % produce an infinite rate. The direct-parametrization default is finite by construction,
            % a declared limit must pass isfinite, and the admissible box itself
            % must be finite. This test is what makes that claim checkable.
            for outputBox = {[-1 1], [-30 50]}
                for rep = [rid.rep.Narx(2, 1), ...
                           rid.rep.Narx(3, 1, "inputDifference", false)]
                    cons = rid.gen.Constraints(rep, ...
                        DirectTest.declare(rep.requiredNames(), ...
                            struct("y_km1", outputBox{1})));
                    tc.verifyTrue(all(isfinite(cons.rate), "all"));
                end
            end
        end

        % --- the target-sequence construction -------------------

        function theTargetCountRespectsItsBoundWithGForcedToOne(tc)
            % The bound:
            %     floor(nHorizon * g * duMax / w) <= nTargets <= nHorizon
            % for an ROI u range of width w. g is pinned to 1 by scripting the
            % stream, so the bound is exact rather than probabilistic.
            %
            % Fails if: a segment overshoots its target (count too high), or the
            % ramp moves slower than g*duMax (count too low).
            L = 10; roi = [0 5]; w = 5;
            for duMax = [1 5 6]
                gen   = DirectTest.roiGen(duMax, L);
                lower = min(floor(L * duMax / w), L);
                for seed = 1:25
                    Zn = DirectTest.gOneStream(seed, L);
                    [~, info] = gen.initialGuesses(wellFormedHistory(0.3), zeros(0, 1), ...
                        "nStarts", 2, "seed", Zn, "roiInputRange", roi);
                    tc.verifyGreaterThanOrEqual(info.nTargets(2, 1), lower, ...
                        sprintf("duMax %g seed %d", duMax, seed));
                    tc.verifyLessThanOrEqual(info.nTargets(2, 1), L);
                end
            end
        end

        function theMeanTargetCountRulesOutAnExtremesOnlyImplementation(tc)
            % The bound alone is satisfied by an implementation that always picks
            % the two extremes of the range -- every hop crosses the whole width, so
            % it sits exactly ON the lower bound. The MEAN is what excludes it.
            %
            % Measured ratio mean/lower converges to 2.30 (L = 10, 30, 60 give
            % 2.38, 2.32, 2.30), not the 3.0 that section 5's w/3 gap argument
            % predicts: each segment also loses about half a sample to the exact
            % landing, which the gap argument does not account for. The band below
            % brackets the measured value and still excludes the mutant at 1.0.
            %
            % Fails if: targets are drawn from the extremes, or from a distribution
            % much narrower than uniform.
            L = 30; roi = [0 5]; lower = 6;      % floor(30 * 1 / 5)
            gen = DirectTest.roiGen(1, L);

            counts = zeros(1, 120);
            for seed = 1:120
                [~, info] = gen.initialGuesses(wellFormedHistory(0.3), zeros(0, 1), ...
                    "nStarts", 2, "seed", DirectTest.gOneStream(seed, L), ...
                    "roiInputRange", roi);
                counts(seed) = info.nTargets(2, 1);
            end
            tc.verifyGreaterThan(mean(counts), 2.0 * lower);
            tc.verifyLessThan(mean(counts), 3.2 * lower);

            % The extremes-only mutant, computed side by side: targets alternate
            % between the ends of the range, so every gap is the full width.
            alt = zeros(1, 2 * (L + 2));
            alt(1:4:end) = 0;            % target at roi(1)
            alt(3:4:end) = 1 - eps;      % target at roi(2)
            [~, mutant] = gen.initialGuesses(wellFormedHistory(0.3), zeros(0, 1), ...
                "nStarts", 2, "seed", ScriptedStream(alt), "roiInputRange", roi);
            tc.verifyLessThanOrEqual(mutant.nTargets(2, 1), lower + 1, ...
                "the extremes-only mutant must sit on the lower bound");
            tc.verifyGreaterThan(mean(counts), mutant.nTargets(2, 1));
        end

        function aSampleLandsOnItsTargetExactly(tc)
            % There is no arrival tolerance: the landing sample IS the target.
            %
            % Fails if: the approach is geometric, or the landing sample is
            % accumulated as u + step instead of assigned. Both leave the sequence
            % near the target but never bit-equal to it.
            level = 1.7;
            gen   = DirectTest.roiGen(1, 12);
            Theta0 = gen.initialGuesses(wellFormedHistory(0.3), zeros(0, 1), ...
                "nStarts", 3, "seed", 5, "targetLevels", level, ...
                "roiInputRange", [0 5]);
            uSeq = gen.toTrajectory(Theta0(1, :).');       % a guided row
            tc.verifyTrue(any(uSeq == level), ...
                "no sample equals the target bit-exactly");
        end

        function theRowsDoNotAllDriftToTheSameWall(tc)
            % The asymmetric rate box is where a uniform-increment walk fails: its
            % mean increment is (-0.1 + 0.6)/2 = +0.25 per sample, so every row
            % drifts to uMax and the starts are not diverse at all.
            %
            % Fails if: the construction is a uniform-increment walk. The mutant is
            % computed here so the contrast is asserted, not assumed.
            cons = rid.gen.Constraints(rid.rep.Narx(2, 1), ...
                       DirectTest.declare(["u1_k" "du1_k" "y_km1"], ...
                           struct("u1_k", [-2 3], "du1_k", [-0.1 0.6])));
            gen  = rid.gen.Direct(cons, 20);
            hist = wellFormedHistory(0.3);

            Theta0 = gen.initialGuesses(hist, zeros(0, 1), "nStarts", 4, "seed", 2);
            finals = zeros(1, 4);
            for iRow = 1:4
                uSeq         = gen.toTrajectory(Theta0(iRow, :).');
                finals(iRow) = max(uSeq(end, :));
            end
            tc.verifyFalse(all(finals > 3 - 0.6), ...
                "every row finished within one rate step of uMax");

            % The retired uniform-increment walk, on the same limits.
            stream = RandStream("twister", "Seed", 2);
            mutantFinals = zeros(1, 4);
            for iRow = 1:4
                u = 0.3;
                for jStep = 1:20
                    u = min(max(u + (-0.1 + 0.7 * rand(stream)), -2), 3);
                end
                mutantFinals(iRow) = u;
            end
            tc.verifyTrue(all(mutantFinals > 3 - 0.6), ...
                "the uniform-increment mutant must pin every row at uMax");
        end

        function theLastRowIsUnguidedEvenWhenTargetLevelsAreGiven(tc)
            % a guided start is guided by what the surrogate already predicts
            % well, so one row stays blind. A single degenerate level makes the
            % distinction visible: guided rows must sit on it, the last must not.
            %
            % Fails if: the last row also draws from targetLevels.
            level  = 1.7;
            gen    = DirectTest.roiGen(1, 15);
            [Theta0, info] = gen.initialGuesses(wellFormedHistory(0.3), zeros(0, 1), ...
                "nStarts", 4, "seed", 6, "targetLevels", level, ...
                "roiInputRange", [0 5]);
            tc.verifyEqual(info.guided, [true true true false]);

            % A guided row's only target is `level`, so it can never pass it -- it
            % ramps toward it and stops. It need not ARRIVE within the horizon: a
            % small g makes the approach slow, which is the construction working,
            % not failing. Being capped is the robust signature.
            for iRow = 1:3
                uSeq = gen.toTrajectory(Theta0(iRow, :).');
                tc.verifyLessThanOrEqual(max(uSeq), level + tc.Tol, ...
                    sprintf("guided row %d passed its only target", iRow));
            end
            % The unguided row draws over the ROI u range and is not capped by it.
            last = gen.toTrajectory(Theta0(4, :).');
            tc.verifyGreaterThan(max(last), level, ...
                "the last row is bound by targetLevels, so it is not unguided");
        end

        function onTheFirstStepEveryRowIsASequenceAndNoneIsAConstantHold(tc)
            % Fails if: an empty thetaPrev produces a constant-hold row, which the
            % construction deliberately no longer has.
            gen = DirectTest.roiGen(1, 12);
            [Theta0, info] = gen.initialGuesses(wellFormedHistory(0.3), zeros(0, 1), ...
                "nStarts", 4, "seed", 8, "roiInputRange", [0 5]);
            tc.verifyEqual(info.warmStart, "none");
            tc.verifyEqual(info.nSequences, 4);
            for iRow = 1:4
                tc.verifyGreaterThan(numel(unique(Theta0(iRow, :))), 1, ...
                    sprintf("row %d is a constant hold", iRow));
            end
        end

        function targetLevelsWithSeveralInputChannelsIsAnError(tc)
            % targetLevels entries are input COMBINATIONS: with several channels the
            % resting output depends on all of them jointly, so only a whole row has
            % a defined output. Drawing per column mixes components of different
            % rows into a combination unrelated to the output grid the surrogate-guided initialization built.
            %
            % Fails if: the per-channel draw is silently kept for MISO, which is
            % invisible at nInputs = 1 where the two readings coincide.
            cons = rid.gen.Constraints(rid.rep.Narx(2, 1, "nInputs", 2), ...
                       DirectTest.declare(["u1_k" "du1_k" "u2_k" "du2_k" "y_km1"], ...
                           struct("u1_k", [-2 3],  "du1_k", [-0.4 0.4], ...
                                  "u2_k", [10 40], "du2_k", [-7 2])));
            gen = rid.gen.Direct(cons, 8);
            tc.verifyError(@() gen.initialGuesses(wellFormedHistory([0 20]), ...
                zeros(0, 1), "nStarts", 4, "targetLevels", [1 20; 2 30]), ...
                "rid:gen:targetLevelsNotDefinedForMiso");
            msg = DirectTest.messageOf(@() gen.initialGuesses( ...
                wellFormedHistory([0 20]), zeros(0, 1), "nStarts", 4, "targetLevels", [1 20; 2 30]));
            tc.verifySubstring(msg, 'synchronized-segment');
        end

        function theSameMisoConfigurationInitializesUnguidedWithoutTargetLevels(tc)
            % The other half, and what stops the guard being over-broad: MISO is not
            % rejected, only GUIDED MISO. Without this a guard that refused all
            % multi-input initialization would pass the test above.
            %
            % Fails if: the guard keys on nInputs alone rather than on
            % targetLevels being supplied as well.
            cons = rid.gen.Constraints(rid.rep.Narx(2, 1, "nInputs", 2), ...
                       DirectTest.declare(["u1_k" "du1_k" "u2_k" "du2_k" "y_km1"], ...
                           struct("u1_k", [-2 3],  "du1_k", [-0.4 0.4], ...
                                  "u2_k", [10 40], "du2_k", [-7 2])));
            gen = rid.gen.Direct(cons, 8);
            [Theta0, info] = gen.initialGuesses(wellFormedHistory([0 20]), zeros(0, 1), ...
                "nStarts", 4, "seed", 3);
            tc.verifyEqual(size(Theta0), [4, gen.nParams()]);
            tc.verifyEqual(info.guided, false(1, 4), ...
                "multi-input initialization is unguided, not refused");
        end

        function aTargetOutsideTheRoiRangeIsClippedNotUsedRaw(tc)
            % the ROI declares its u and y bounds independently, so a level
            % mapped through the static map can fall outside. Clip and report; never
            % absorb silently.
            %
            % Fails if: the raw level is used, which would put the row outside the
            % ROI u range the rest of the design assumes.
            gen = DirectTest.roiGen(1, 15);
            Theta0 = gen.initialGuesses(wellFormedHistory(0.3), zeros(0, 1), ...
                "nStarts", 3, "seed", 9, "targetLevels", 4.5, ...  % outside [0 3]
                "roiInputRange", [0 3]);
            uSeq = gen.toTrajectory(Theta0(1, :).');
            tc.verifyLessThanOrEqual(max(uSeq), 3 + tc.Tol);
            tc.verifyEqual(uSeq(end), 3, "AbsTol", tc.Tol);
        end

        % --- the feasible set --------------------------------------------------

        function theFeasibleSetIsExactlyTheTrajectoryConstraintSet(tc)
            % The claim the optimizer relies on, as an equivalence over draws that
            % deliberately straddle the boundary.
            %
            % THE DRAW MIX IS THE TEST'S REAL CONTENT. Uniform draws from the
            % amplitude box essentially never satisfy a rate limit of 0.4 over a
            % width-5 box, so a uniform-only sample tests the "outside" branch and
            % nothing else -- it passes while proving nothing. Three families:
            % rate-feasible walks (members by construction), uniform draws
            % (non-members almost surely), and walks perturbed by noise of the order
            % of the rate limit itself, which is what actually probes the boundary.
            gen  = DirectTest.siso(6);
            hist = wellFormedHistory(0.3);
            [lb, ub, A, b] = gen.feasibleSet(hist);

            stream = RandStream("twister", "Seed", 7);
            draws  = cell(1, 0);
            for iDraw = 1:120
                walk  = DirectTest.rateFeasibleWalk(gen, hist, stream);
                draws{end+1} = walk;                                   %#ok<AGROW>
                draws{end+1} = lb + (ub - lb) .* rand(stream, size(lb)); %#ok<AGROW>
                draws{end+1} = walk + 0.3 * randn(stream, size(walk));  %#ok<AGROW>
            end

            nMember = 0;
            for iDraw = 1:numel(draws)
                theta = draws{iDraw};
                inSet = DirectTest.isMember(theta, lb, ub, A, b);
                ok    = DirectTest.trajectoryRespectsLimits( ...
                            gen, reshape(theta, gen.nHorizon, gen.nInputs()), hist);
                tc.verifyEqual(inSet, ok, ...
                    sprintf("draw %d: declared feasible set and trajectory " + ...
                            "limits disagree", iDraw));
                nMember = nMember + inSet;
            end
            % Non-vacuity: both classes must actually occur, or the equivalence
            % above is satisfied by an accident of the sample.
            tc.verifyGreaterThan(nMember, 0);
            tc.verifyLessThan(nMember, numel(draws));
        end

        function theDeclaredSetIsNonEmpty(tc)
            for L = [1 2 7]
                gen = DirectTest.siso(L);
                [lb, ub, ~, ~] = gen.feasibleSet(wellFormedHistory(0.3));
                tc.verifyTrue(all(lb <= ub));
            end
        end

        function theFirstSampleIsBoundedByTheLastAppliedInput(tc)
            % |u_hat(k) - u(k-1)| <= duMax is a BOUND, not a row of A (section 6).
            gen  = DirectTest.siso(5);          % amplitude [-2 3], rate [-0.4 0.4]
            [lb, ub, ~, ~] = gen.feasibleSet(wellFormedHistory(0.3));
            tc.verifyEqual(lb(1), -0.1, "AbsTol", tc.Tol);
            tc.verifyEqual(ub(1),  0.7, "AbsTol", tc.Tol);
            % ... and only the first: the rest carry the amplitude box alone.
            tc.verifyEqual(lb(2:end), -2 * ones(4, 1), "AbsTol", tc.Tol);
            tc.verifyEqual(ub(2:end),  3 * ones(4, 1), "AbsTol", tc.Tol);
        end

        function theAmplitudeBoxStillWinsWhenItIsTheTighterOne(tc)
            % Intersection, not replacement: near the edge of the amplitude box the
            % rate step must not open the box up.
            gen = DirectTest.siso(4);           % amplitude [-2 3], rate [-0.4 0.4]
            [~, ub, ~, ~] = gen.feasibleSet(wellFormedHistory(2.9));
            tc.verifyEqual(ub(1), 3, "AbsTol", tc.Tol);
        end

        function anUnreachableFirstSampleIsReportedNotClamped(tc)
            % Never silently clamp. u(k-1) further outside the amplitude box than
            % one rate step leaves no admissible first sample at all.
            gen = DirectTest.siso(4);           % amplitude [-2 3], rate [-0.4 0.4]
