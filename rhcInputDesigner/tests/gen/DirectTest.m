        function anAsymmetricRateBoxGivesTwoDifferentRowBlocks(tc)
            % An actuator that opens faster than it closes is the normal case; a
            % single |.| <= duMax block would silently symmetrize it.
            cons = rid.gen.Constraints(rid.rep.Narx(2, 1), ...
                       DirectTest.declare(["u1_k" "du1_k" "y_km1"], ...
                           struct("u1_k", [-2 3], "du1_k", [-0.1 0.6])));
            gen  = rid.gen.Direct(cons, 3);
            [~, ~, ~, b] = gen.feasibleSet(wellFormedHistory(0));
            tc.verifyEqual(b, [0.6; 0.6; 0.1; 0.1], "AbsTol", tc.Tol);
        end

        function eachChannelGetsItsOwnBlockAndItsOwnLimits(tc)
            % The kron blocking, checked by making the two channels disagree about
            % everything: a leaked index would show up as the wrong bound.
            cons = rid.gen.Constraints(rid.rep.Narx(2, 1, "nInputs", 2), ...
                       DirectTest.declare(["u1_k" "du1_k" "u2_k" "du2_k" "y_km1"], ...
                           struct("u1_k", [-2 3],  "du1_k", [-0.4 0.4], ...
                                  "u2_k", [10 40], "du2_k", [-7 2])));
            gen = rid.gen.Direct(cons, 3);
            [lb, ub, A, b] = gen.feasibleSet(wellFormedHistory([0 20]));

            tc.verifyEqual(lb, [-0.4; -2; -2;  13; 10; 10], "AbsTol", tc.Tol);
            tc.verifyEqual(ub, [ 0.4;  3;  3;  22; 40; 40], "AbsTol", tc.Tol);
            tc.verifyEqual(b, [0.4; 0.4; 2; 2; 0.4; 0.4; 7; 7], "AbsTol", tc.Tol);
            % Channel 1's rows must not touch channel 2's variables.
            tc.verifyEqual(full(A(1, 4:6)), [0 0 0]);
            tc.verifyEqual(full(A(3, 1:3)), [0 0 0]);
        end

