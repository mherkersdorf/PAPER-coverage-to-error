            % not undefined, and the user is told what to declare.
            tc.verifyError(@() gen.feasibleSet(wellFormedHistory(zeros(0, 1))), ...
                "rid:gen:missingInitialInput");
            tc.verifySubstring( ...
                DirectTest.messageOf(@() gen.feasibleSet(wellFormedHistory(zeros(0, 1)))), ...
                "unrecorded, not undefined");
        end

