    methods (Static, Access = private)

        function cons = constraints(nInputs)
            %CONSTRAINTS  amplitude [-2 3] and rate [-0.4 0.4] on every channel.
            if nInputs == 1
                rep   = rid.rep.Narx(2, 1);
                names = ["u1_k" "du1_k" "y_km1"];
            else
                rep   = rid.rep.Narx(2, 1, "nInputs", nInputs);
                names = rep.requiredNames();
            end
            over = struct();
            for name = names
                if startsWith(name, "du"), over.(name) = [-0.4 0.4]; end
            end
            cons = rid.gen.Constraints(rep, DirectTest.declare(names, over));
        end

        function gen = siso(nHorizon)
            gen = rid.gen.Direct(DirectTest.constraints(1), nHorizon);
        end

        function gen = miso(nHorizon)
            gen = rid.gen.Direct(DirectTest.constraints(2), nHorizon);
        end

        function roi = declare(names, overrides)
            arguments
                names     (1,:) string
                overrides (1,1) struct = struct()
            end
            roi = struct();
            for iName = 1:numel(names)
                roi.(names(iName)) = [-2 3];
            end
            given = string(fieldnames(overrides)).';
            for iGiven = 1:numel(given)
                roi.(given(iGiven)) = overrides.(given(iGiven));
            end
        end

        function tf = isMember(theta, lb, ub, A, b)
            %ISMEMBER  Membership of the DECLARED set, with a numerical tolerance.
            tol = 1e-12;
            tf  = all(theta >= lb - tol) && all(theta <= ub + tol) && ...
                  (isempty(b) || all(A * theta <= b + tol));
        end

        function tf = trajectoryRespectsLimits(gen, uSeq, hist)
            %TRAJECTORYRESPECTSLIMITS  The limits themselves, computed independently
            %   of the lb/ub/A/b the code under test produced.
            tol  = 1e-12;
            cons = gen.constraints;
            tf   = true;
            for cIn = 1:size(uSeq, 2)
                u  = uSeq(:, cIn);
                du = [u(1) - hist.u(end, cIn); diff(u)];
                tf = tf && all(u  >= cons.amplitude(cIn, 1) - tol) ...
                        && all(u  <= cons.amplitude(cIn, 2) + tol) ...
                        && all(du >= cons.rate(cIn, 1) - tol) ...
                        && all(du <= cons.rate(cIn, 2) + tol);
            end
        end

        function theta = rateFeasibleWalk(gen, hist, stream)
            %RATEFEASIBLEWALK  A feasible fixture: increments inside the rate box,
            %   cumulated, and kept inside the amplitude box by construction.
            %
            %   The increment range is intersected with what the amplitude box still
            %   allows, so the walk never needs reflecting and is feasible by
            %   construction rather than by rejection.
            cons = gen.constraints;
            uSeq   = zeros(gen.nHorizon, gen.nInputs());
            for cIn = 1:gen.nInputs()
                u = hist.u(end, cIn);
                for jStep = 1:gen.nHorizon
                    lo = max(cons.rate(cIn, 1), cons.amplitude(cIn, 1) - u);
                    hi = min(cons.rate(cIn, 2), cons.amplitude(cIn, 2) - u);
                    u  = u + lo + (hi - lo) * rand(stream);
                    uSeq(jStep, cIn) = u;
                end
            end
            theta = uSeq(:);
        end

        function gen = roiGen(duMax, nHorizon)
            %ROIGEN  amplitude [-1 6], rate +-duMax, so an ROI u range of [0 5] fits.
            cons = rid.gen.Constraints(rid.rep.Narx(2, 1), ...
                       DirectTest.declare(["u1_k" "du1_k" "y_km1"], ...
                           struct("u1_k", [-1 6], "du1_k", [-duMax duMax])));
            gen  = rid.gen.Direct(cons, nHorizon);
        end

        function stream = gOneStream(seed, nHorizon)
            %GONESTREAM  Pseudo-random targets with the speed fraction pinned to 1.
            %
            %   The draw order per target is (target, g), and g = 1 - rand, so a
            %   scripted 0 in every second slot forces g = 1 exactly.
            rs   = RandStream("twister", "Seed", seed);
            vals = zeros(1, 2 * (nHorizon + 2));
            vals(1:2:end) = rand(rs, 1, nHorizon + 2);
            stream = ScriptedStream(vals);
        end

        function msg = messageOf(fh)
            try
                fh();
                msg = '';
            catch err
                msg = err.message;
            end
        end

