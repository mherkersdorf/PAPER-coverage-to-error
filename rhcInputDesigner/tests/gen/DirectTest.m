                "rid:gen:emptyFeasibleSet");
            msg = DirectTest.messageOf(@() gen.feasibleSet(wellFormedHistory(9)));
            tc.verifySubstring(msg, 'u1');
        end

        function theRateConstraintIsOnePairOfRowsPerConsecutiveSample(tc)
            % Exactly at the sample rate: nHorizon-1 differences per channel, two
            % rows each because the rate box need not be symmetric.
            gen = DirectTest.miso(5);
            [~, ~, A, b] = gen.feasibleSet(wellFormedHistory([0 0]));
            tc.verifyEqual(size(A), [2 * 2 * 4, 10]);
