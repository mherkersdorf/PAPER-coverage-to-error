classdef CanaryTest < matlab.unittest.TestCase
%CANARYTEST  The canary harness: rebuild a Setup from a spec, run, compare.
%
%   WHAT A CANARY IS HERE. `tests/data/canaries/*.json` is a DECLARATIVE SPEC plus
%   expected outputs: the class name and constructor arguments of each `rid.rhc.Setup`
%   member, and `Q`, the refinement fields, `epsReqInitial` and `hist0` as explicit
%   numbers. This class rebuilds the `Setup`
%   from that spec, runs `rid.rhc.run`, and compares.
%
%   IT IS NOT `rid.io.replay`, DELIBERATELY. Section 4's `replay` reproduces from a
%   LIVE record; JSON cannot carry a `Setup` holding `Surrogate` and `Representation`
%   objects, and `run.json` is a summary with no setup, no `Q` and no `u`. Two
%   mechanisms, two purposes.
%
%   NO SEED AND NO TOOLBOX GENERATOR PRODUCES A CANARY DATUM. `Q` is frozen as
%   numbers in every canary rather than regenerated by `lhsdesign`. A canary that a
%   MATLAB release note can turn red is one that gets switched off, which section 5
%   names as how canaries die -- and the two criteria below are the two answers to
%   that: the value canary keeps the toolbox out of its replay path entirely, the
%   path canary admits `fmincon` and reads only what `fmincon` cannot move.
%
%   TOLERANCE IS 1e-12 RELATIVE, the golden-vector convention. Whether a
%   canary reproduced bit-exactly when it was frozen is a question for its generation record,
%   never the acceptance criterion.
%
%   EACH CANARY DECLARES ITS OWN ACCEPTANCE CRITERION, which is why there
%   are two parameters and two pairs of test methods rather than one of each.
%   `valueCanary` is the paragraph above: no toolbox in the replay path, so every
%   number is ours and `1e-12` is meaningful. `pathCanary` runs `rid.opt.MultiStart`
%   and therefore `fmincon`, and freezes the PATH the run took -- the affine tier,
%   the gradient path, monotonicity within a segment, the reset count, evaluation
%   counts to an order of magnitude, and the final `J` in a declared band. It
%   deliberately does NOT freeze `u`, `theta` or `J`: `J` is not convex, so
%   a changed iterate path can land in a different local optimum and the committed
%   input jumps discontinuously. No tolerance covers a basin switch, so the
%   criterion changes in KIND rather than in size.
%
%   WHEN ONE FAILS, decide first whether the change was intended. If not, fix the
%   code. If it was, re-record with `generateCanary` in a commit touching only the
%   canary files, with a one-line reason (canary replay, section 5).

    properties (TestParameter)
        % LISTED, NOT DISCOVERED. A parameter built by scanning the directory would
        % run whatever it found and, on an empty directory, run nothing at all while
        % reporting green -- the failure the golden-file rule was written about, one directory up.
        % `everyCanaryFileIsExercised` compares these lists against the directory and
        % reads them back from the class metadata, so these literals are the only copy.
        %
        % TWO LISTS, BECAUSE THERE ARE TWO ACCEPTANCE CRITERIA. Which list a
        % canary is on decides which methods run against it; a single list plus a
        % criterion read at run time would make the choice depend on a field of the
        % file being checked, so a file that lost its criterion would quietly fall
        % back to the wrong test.
        valueCanary = {'sisoNarxBudget'}
        pathCanary  = {'sisoNarxMultiStart'}
    end

    methods (Test)

        function theStoredRunIsReproduced(tc, valueCanary)
            % Fails if: any behaviour anywhere below rid.rhc.run moves the designed
            % signal, J, the active-set counts or the certification report.
            spec = CanaryTest.readCanary(string(valueCanary));
            relTol = spec.tolerance.relative;

            [setup, env] = CanaryTest.buildSetup(spec);
            opts = CanaryTest.marshal(spec.options, env);
            r    = rid.rhc.run([], setup, env.hist0, opts);

            e = spec.expected;
            tc.verifyEqual(r.status, string(e.status), "status");
            tc.verifyEqual(r.nSteps, e.nSteps, "nSteps");

            CanaryTest.compare(tc, r.J,      e.J,                 "J",       relTol);
            CanaryTest.compare(tc, r.Jtrace, e.Jtrace.column,     "Jtrace",  relTol);
            CanaryTest.compare(tc, r.hist.u, e.u.matrix,          "hist.u",  relTol);

            s = e.steps;
            CanaryTest.compare(tc, [r.steps.JBefore].', s.JBefore.column, ...
                "steps.JBefore", relTol);
            CanaryTest.compare(tc, [r.steps.JAfter].',  s.JAfter.column, ...
                "steps.JAfter",  relTol);
            CanaryTest.compare(tc, [r.steps.nActive].', s.nActive.column, ...
                "steps.nActive", relTol);
            CanaryTest.compare(tc, vertcat(r.steps.uApplied), s.uApplied.matrix, ...
                "steps.uApplied", relTol);
            CanaryTest.compare(tc, horzcat(r.steps.theta).', s.theta.matrix, ...
                "steps.theta", relTol);
            CanaryTest.compare(tc, double([r.steps.coverageReset].'), ...
                s.coverageReset.column, "steps.coverageReset", relTol);

            c = e.certification;
            tc.verifyEqual(r.certification.mode, string(c.mode), "certification.mode");
            CanaryTest.compare(tc, double(r.certification.isSatisfied), c.isSatisfied, ...
                "certification.isSatisfied", relTol);
            CanaryTest.compare(tc, r.certification.epsReqMax, c.epsReqMax, ...
                "certification.epsReqMax", relTol);
            CanaryTest.compare(tc, r.certification.fillDistanceQ, c.fillDistanceQ, ...
                "certification.fillDistanceQ", relTol);
            CanaryTest.compare(tc, r.certification.bound, c.bound, ...
                "certification.bound", relTol);

            CanaryTest.compare(tc, numel(r.eventLog), e.nEvents, "nEvents", relTol);
            CanaryTest.compare(tc, numel(r.warnings), e.nWarnings, "nWarnings", relTol);
            nReset = sum(string({r.eventLog.kind}) == "coverageReset");
            CanaryTest.compare(tc, nReset, e.nCoverageResets, "nCoverageResets", relTol);
        end

        function theStoredRunIsNotDegenerate(tc, valueCanary)
            % The coverage reset AND THE FIRST-CANARY RULE, APPLIED TO THE ARTEFACT ITSELF. A canary that
            % certifies early sits in the regime where every step poses the
            % optimizer the same problem, the input freezes into a repeat, and the
            % reference is a constant signal that passes forever while testing
            % nothing. This reads the STORED expectations, so a re-recording into
            % that regime is caught in the commit that performs it.
            %
            % Fails if: a future re-recording lands on a configuration whose J stops
            % moving, whose input repeats, or which resets its coverage.
            e = CanaryTest.readCanary(string(valueCanary)).expected;

            tc.verifyEqual(e.nCoverageResets, 0, ...
                "a canary in the degenerate coverage-reset regime tests nothing");
            tc.verifyTrue(all(diff(e.Jtrace.column) < 0), ...
                sprintf("J must fall at every step; Jtrace = %s", ...
                        mat2str(e.Jtrace.column.', 6)));
            tc.verifyGreaterThan(numel(unique(e.u.matrix)), 2, ...
                "the designed input must move, or the canary is a constant signal");
        end

        function theStoredPathIsReproduced(tc, pathCanary)
            % THE PATH CANARY OF THE PATH CANARY. `fmincon` IS in this replay path, so what
            % is compared is what a changed iterate path cannot move: the affine
            % tier, the gradient path, monotonicity within a segment, the reset
            % count, evaluation counts to an order of magnitude, and the final `J`
            % inside a declared band.
            %
            % `u`, `theta` and `J` ARE ABSENT ON PURPOSE. `J` is a minimum over
            % samples and is not convex; a different iterate path can land
            % in a different local optimum and the committed input jumps. No
            % tolerance covers a basin switch, and adding these "for strength"
            % would produce exactly the flapping canary that section 5 says gets
            % switched off.
            %
            % Fails if: the affine probe stops returning "affine", the objective
            % stops offering its gradient, the loop re-probes when it should not,
            % the criterion evaluation count blows up by a decade, a coverage
            % reset appears, J stops falling inside a segment, or the run ends
            % somewhere far from where it ends now.
            spec = CanaryTest.readCanary(string(pathCanary));
            tc.assertEqual(string(spec.criterion), "path", ...
                "a file listed as a path canary must declare criterion ""path""");

            [setup, env] = CanaryTest.buildSetup(spec);
            opts = CanaryTest.marshal(spec.options, env);
            r    = rid.rhc.run([], setup, env.hist0, opts);

            e     = spec.expected;
            acc   = spec.acceptance;
            band  = CanaryTest.marshal(acc.JFinalBand, struct());
            nStep = r.nSteps;

            % --- the shape of the run: discrete, exact --------------------
            tc.verifyEqual(r.status, string(e.status), "status");
            tc.verifyEqual(r.nSteps, e.nSteps, "nSteps");
            tc.verifyEqual(r.steps(1).optDiag.solver, string(e.solver), ...
                "the spec must have built the solver the canary is about");
            tc.verifyEqual(r.steps(1).optDiag.nStarts, e.nStarts, "nStarts");
            tc.verifyEqual(numel(r.eventLog), e.nEvents, "nEvents");
            tc.verifyEqual(numel(r.warnings), e.nWarnings, "nWarnings");
            tc.verifyEqual(r.certification.mode, string(e.certification.mode), ...
                "certification.mode");
            tc.verifyEqual(double(r.certification.isSatisfied), ...
                e.certification.isSatisfied, "certification.isSatisfied");

            % THE RESET COUNT, read from both places that record it. The event
            % log and the step flags are written independently, so a disagreement
            % between them is itself worth catching.
            nReset = sum(string({r.eventLog.kind}) == "coverageReset");
            tc.verifyEqual(nReset, e.nCoverageResets, "nCoverageResets");
            tc.verifyEqual(sum([r.steps.coverageReset]), e.nCoverageResets, ...
                "steps.coverageReset disagrees with the event log");

            % --- the gradient path, per step ------------------------------
            tier = string({r.steps.affineTier});
            tc.verifyEqual(tier, CanaryTest.marshal(e.affineTier, struct()), ...
                sprintf("affineTier: got [%s]", strjoin(tier, " | ")));
            gpath = string({r.steps.gradientPath});
            tc.verifyEqual(gpath, CanaryTest.marshal(e.gradientPath, struct()), ...
                sprintf("gradientPath: got [%s]", strjoin(gpath, " | ")));
            % nShell reported at every step is the three-output arity, which
            % is the same fact as the analytic path seen from the objective's side.
            tc.verifyTrue(all(isfinite([r.steps.deadOnArrival])), ...
                "deadOnArrival is NaN somewhere: the objective stopped " + ...
                "reporting nShell, so the three-output path was not taken");

            % --- monotonicity, a PROPERTY and not a value -----------------
            % Within a step nothing can change the state between JBefore and
            % JAfter, so that half needs no segment logic. Across a step boundary
            % J is comparable only when no surrogate update, resolution change or
            % coverage reset intervened -- the segments,
            % discovered from the event log rather than assumed.
            slack    = 1 + 1e-12;
            JBefore  = [r.steps.JBefore].';
            JAfter   = [r.steps.JAfter].';
            tc.verifyTrue(all(JAfter <= JBefore * slack), sprintf( ...
                "J rose inside a step: JBefore = %s, JAfter = %s", ...
                mat2str(JBefore.', 6), mat2str(JAfter.', 6)));

            breaks = CanaryTest.segmentBreaks(r);
            for kStep = 1:(nStep - 1)
                if breaks(kStep)
                    continue
                end
                tc.verifyLessThanOrEqual(JBefore(kStep + 1), ...
                    JAfter(kStep) * slack, sprintf( ...
                    "J rose from step %d to step %d inside one segment: " + ...
                    "%.17g -> %.17g", kStep, kStep + 1, JAfter(kStep), ...
                    JBefore(kStep + 1)));
            end

            % nActive falls with J and reaches zero exactly at certification, so
            % it says the same thing one level up; a positive final count is the
            % run declaring it never certified.
            nActive = [r.steps.nActive].';
            for kStep = 1:(nStep - 1)
                if breaks(kStep)
                    continue
                end
                tc.verifyLessThanOrEqual(nActive(kStep + 1), nActive(kStep), ...
                    sprintf("nActive rose from step %d to step %d: %s", ...
                            kStep, kStep + 1, mat2str(nActive.')));
            end
            tc.verifyGreaterThan(nActive(end), 0, ...
                "every supporting point was resolved: the run certified, which " + ...
                "is the coverage reset's degenerate regime, not this configuration");

            % --- evaluation counts, TO AN ORDER OF MAGNITUDE --------------
            % A ratio band would flap: the measured per-step spread under a
            % changed iterate path is a factor of ~29. One decade
            % of slack either side of the stored order survives that and still
            % catches what the path canary names -- a count that blows up, or a solve that
            % never called the objective at all.
            nEval  = [r.steps.nEvaluations].';
            stored = CanaryTest.marshal(e.nEvaluations, struct());
            tc.assertTrue(all(nEval > 0), sprintf( ...
                "the objective was never evaluated at some step: %s", ...
                mat2str(nEval.')));
            dGot    = floor(log10(nEval));
            dWanted = floor(log10(stored));
            offBy   = abs(dGot - dWanted) > acc.evaluationDecadeSlack;
            tc.verifyFalse(any(offBy), sprintf( ...
                "nEvaluations moved by more than %d decade(s) at step(s) %s: " + ...
                "got %s, the canary recorded %s", acc.evaluationDecadeSlack, ...
                mat2str(find(offBy).'), mat2str(nEval.'), mat2str(stored.')));

            % The aggregate is the sharper half: the measured spread of the TOTAL
            % is only a factor of ~2.2, so a factor of ten here is a real bound.
            total = sum(nEval);
            tc.verifyGreaterThanOrEqual(total, ...
                e.nEvaluationsTotal / acc.evaluationTotalFactor, sprintf( ...
                "total nEvaluations = %d; the canary recorded %d", total, ...
                e.nEvaluationsTotal));
            tc.verifyLessThanOrEqual(total, ...
                e.nEvaluationsTotal * acc.evaluationTotalFactor, sprintf( ...
                "total nEvaluations = %d; the canary recorded %d", total, ...
                e.nEvaluationsTotal));

            % --- the final J, INSIDE A BAND, never at a tolerance ---------
            % The band is CHOSEN, not derived.
            tc.verifyGreaterThanOrEqual(r.J, band(1), sprintf( ...
                "final J = %.17g is below the declared band [%g, %g]", ...
                r.J, band(1), band(2)));
            tc.verifyLessThanOrEqual(r.J, band(2), sprintf( ...
                "final J = %.17g is above the declared band [%g, %g]", ...
                r.J, band(1), band(2)));

            % The designed input must still be an input. This is the one live
            % non-degeneracy check that cannot be read off the stored file.
            tc.verifyGreaterThan(numel(unique(r.hist.u)), 2, ...
                "the designed input is constant, so the canary is a constant " + ...
                "signal that passes forever");
        end

        function theStoredPathIsNotDegenerate(tc, pathCanary)
            % The coverage reset AND THE PATH CANARY, APPLIED TO THE ARTEFACT ITSELF, read from the
            % STORED file so that a re-recording into a useless regime fails in
            % the commit that performs it rather than silently thereafter.
            %
            % Fails if: a future re-recording certifies early, resets its
            % coverage, loses the analytic gradient path -- which is the entire
            % reason this second canary exists -- or declares a band that admits
            % J = 0.
            spec = CanaryTest.readCanary(string(pathCanary));
            e    = spec.expected;
            band = CanaryTest.marshal(spec.acceptance.JFinalBand, struct());

            tc.verifyEqual(e.nCoverageResets, 0, ...
                "a canary in the degenerate coverage-reset regime tests nothing");
            tc.verifyEqual(e.certification.isSatisfied, 0, ...
                "a canary that certifies is a constant signal from then on");
            tc.verifyGreaterThan(band(1), 0, ...
                "a band open to J = 0 admits the early certification the coverage reset " + ...
                "warns about, so it would not detect it");
            tc.verifyLessThan(band(2), 1, ...
                "a band reaching J = 1 admits a run that designed nothing");

            tier  = CanaryTest.marshal(e.affineTier, struct());
            gpath = CanaryTest.marshal(e.gradientPath, struct());
            tc.verifyEqual(tier(1), "affine", sprintf( ...
                "the affine probe recorded %s; a path canary whose tier is not " + ...
                "affine takes the finite-difference fall-back and covers " + ...
                "nothing the first canary does not", tier(1)));
            tc.verifyTrue(all(gpath == "analytic"), sprintf( ...
                "gradientPath recorded [%s]; this canary exists to exercise " + ...
                "the ANALYTIC path", strjoin(gpath, " | ")));
        end

        function everyCanaryFileIsExercised(tc)
            % The listing above is the test's, the directory is the artefact's, and a
            % file present in one and not the other is how a canary stops running
            % without anybody noticing.
            found = string({dir(fullfile(CanaryTest.canaryDir(), "*.json")).name});
            found = sort(erase(found, ".json"));
            tc.assertNotEmpty(found, ...
                "tests/data/canaries holds no canary at all");
            tc.verifyEqual(found, CanaryTest.parameterNames("all"), ...
                "tests/data/canaries and the canary TestParameters have diverged");
            % A file on BOTH lists would be checked under two criteria, one of
            % which must be the wrong one.
            tc.verifyEmpty(intersect(CanaryTest.parameterNames("valueCanary"), ...
                                     CanaryTest.parameterNames("pathCanary")), ...
                "a canary is listed as both a value canary and a path canary");
        end

    end

    methods (Static)

        function names = parameterNames(which)
            %PARAMETERNAMES  A canary TestParameter, read from the metadata.
            %
            %   Read rather than restated: a second literal would be a second thing
            %   to keep in step, and the whole point of the check above is that the
            %   lists and the directory cannot drift apart unnoticed.
            %
            %   Inputs:
            %       which  (1x1) string  "valueCanary", "pathCanary", or "all"
            %   Outputs:
            %       names  (1xN) string  sorted basenames
            arguments
                which (1,1) string {mustBeMember(which, ...
                    ["valueCanary", "pathCanary", "all"])} = "all"
            end
            if which == "all"
                names = sort([CanaryTest.parameterNames("valueCanary"), ...
                              CanaryTest.parameterNames("pathCanary")]);
                return
            end
            props = meta.class.fromName("CanaryTest").PropertyList;
            names = sort(string(props(string({props.Name}) == which).DefaultValue));
            names = reshape(names, 1, []);
        end

        function breaks = segmentBreaks(r)
            %SEGMENTBREAKS  Where `J` stops being comparable across a step.
            %
            %   `breaks(k)` is true when something logged at step `k` makes step
            %   `k + 1` incomparable with it: a surrogate update or a resolution
            %   change (invariant 3) or a budget-mode coverage reset. The
            %   segments are DISCOVERED from the event log, never assumed, so the
            %   check keeps its meaning if a re-recording ever admits an update.
            %
            %   Inputs:  r       (1x1) struct   the run result
            %   Outputs: breaks  (nStepsx1) logical
            breaks = false(r.nSteps, 1);
            incomparable = ["surrogateUpdate", "resolutionChange", "coverageReset"];
            for iEvent = 1:numel(r.eventLog)
                ev = r.eventLog(iEvent);
                if ismember(ev.kind, incomparable) && ev.step >= 1 && ev.step <= r.nSteps
                    breaks(ev.step) = true;
                end
            end
        end

        function d = canaryDir()
            d = fullfile(fileparts(mfilename("fullpath")), "data", "canaries");
        end

        function spec = readCanary(name)
            %READCANARY  Decode one canary file.
            path = fullfile(CanaryTest.canaryDir(), name + ".json");
            spec = jsondecode(fileread(path));
        end

        function [setup, env] = buildSetup(spec)
            %BUILDSETUP  Rebuild the twelve members of the single-setup rule from the spec.
            %
            %   `data` is built first, then `setup` in the file's own key order, so
            %   that a {"ref": ...} never points forward.
            env = struct();
            for name = string(fieldnames(spec.data)).'
                env.(name) = CanaryTest.marshal(spec.data.(name), env);
            end
            for name = string(fieldnames(spec.setup)).'
                env.(name) = CanaryTest.marshal(spec.setup.(name), env);
            end
            % qInfo IS "supplied" IN EVERY CANARY SPEC, regardless of what
            % generated Q when the file was frozen: the canary specification already forbids any
            % toolbox call at replay, so from the harness's own perspective Q
            % always arrives as explicit numbers, never through
            % rid.roi.supportingPoints.
            setup = rid.rhc.Setup(env.srg, env.rep, env.nrm, env.roi, env.Q, ...
                                  env.fields, env.gen, env.sol, env.state, ...
                                  env.sch, env.fieldSch, env.qInfo);
        end

        function value = marshal(node, env)
            %MARSHAL  One JSON node into the MATLAB value the spec declares.
            %
            %   The tags exist because `jsondecode` cannot express the difference
            %   that matters: a JSON array of numbers is always a column, and a
            %   (1 x 2) ROI range, a (nSup x 1) field and an (nSup x nDim) Q are
            %   three different shapes the constructors will not accept
            %   interchangeably.
            if isstruct(node) && isscalar(node)
                if isfield(node, "class")
                    args  = CanaryTest.marshalArgs(node.args, env);
                    value = feval(node.class, args{:});
                elseif isfield(node, "ref")
                    value = env.(string(node.ref));
                elseif isfield(node, "row")
                    value = reshape(node.row, 1, []);
                elseif isfield(node, "column")
                    value = reshape(node.column, [], 1);
                elseif isfield(node, "matrix")
                    value = node.matrix;
                elseif isfield(node, "strings")
                    value = reshape(string(node.strings), 1, []);
                else
                    value = struct();
                    for name = string(fieldnames(node)).'
                        value.(name) = CanaryTest.marshal(node.(name), env);
                    end
                end
            elseif ischar(node)
                value = string(node);
            else
                value = node;
            end
        end

        function args = marshalArgs(raw, env)
            %MARSHALARGS  A JSON argument list into a cell of MATLAB values.
            if isempty(raw)
                args = {};
            elseif iscell(raw)
                args = cellfun(@(a) CanaryTest.marshal(a, env), raw, ...
                               "UniformOutput", false);
            elseif isstruct(raw)
                args = arrayfun(@(a) CanaryTest.marshal(a, env), raw, ...
                                "UniformOutput", false);
            else
                args = num2cell(raw);
            end
            args = reshape(args, 1, []);
        end

        function compare(tc, actual, expected, name, relTol)
            %COMPARE  Verify one quantity and NAME THE FIRST DIVERGENCE.
            %
            %   Section 4 requires `replay`'s diff to say where a run diverged
            %   rather than that it did; the same is worth having here, where the
            %   alternative is a bare "values differ" over a 6 x 4 matrix.
            if numel(expected) ~= numel(actual)
                tc.verifyEqual(size(actual), size(expected), sprintf( ...
                    "%s has size %s; the canary expects %s. A SHAPE that moved " + ...
                    "is a behaviour change like any other.", name, ...
                    mat2str(size(actual)), mat2str(size(expected))));
                return
            end
            expected = reshape(expected, size(actual));
            scale    = max(abs(expected), abs(actual));
            deviation = abs(actual - expected);
            bad      = deviation > relTol * max(scale, realmin);
            if any(bad(:))
                iFirst = find(bad, 1);
                message = sprintf( ...
                    "%s diverged first at linear index %d: got %.17g, expected " + ...
                    "%.17g (relative %.3g, tolerance %g).", name, iFirst, ...
                    actual(iFirst), expected(iFirst), ...
                    deviation(iFirst) / max(scale(iFirst), realmin), relTol);
            else
                message = name;
            end
            tc.verifyEqual(actual, expected, "RelTol", relTol, message);
        end

    end

end
